export interface Run { x: number; y: number; w: number; c: string }

export function toRuns(frame: string[]): Run[] {
  const runs: Run[] = [];
  frame.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x] ?? '.';
      let w = 1;
      while (x + w < row.length && (row[x + w] ?? '.') === c) w++;
      if (c !== '.') runs.push({ x, y, w, c });
      x += w;
    }
  });
  return runs;
}
